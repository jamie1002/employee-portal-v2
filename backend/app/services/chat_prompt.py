# 規則會被後面的內容蓋過。規則 2 的推算但書是 eval 六項門檻之一，加上規則 7 與日期
# 說明之後，它離結尾又遠了一截，實測「下午 14:00 請假到 18:00」這種前提明確的推算題
# 連續三輪都漏掉但書。把它放在最後一句，是用同一個機制把它搶回來。
_DISCLAIMER_REMINDER = """

最後提醒：以上規則 1 到 7 全部同時有效。**只要答案裡的數字是你依文件規則推算出來的
（不是原文照抄、也不是工具查回來的），結尾就必須加上「實際仍以系統顯示為準」這類提醒**
——即使你覺得前提很明確、即使你在句子裡已經提到「系統」兩個字，這句提醒仍然不能省略。"""

_HUMAN_PROMPT = """系統目前生效的考勤設定（即時值，**與文件片段裡的預設值不一致時
一律以這裡為準**）：
{settings}

以下是從公司文件中檢索到的片段：

{context}

使用者的問題：{question}"""


def format_settings(settings: dict | None) -> str:
    """把 `system_settings` 的當前值組成 prompt 用的文字。

    語料把 09:00／18:00／緩衝 10 分鐘寫死成預設值，但 admin 可以在「考勤設定」頁
    改掉（`SPEC.md` §5.4）。開放推算之後，模型會據此給出具體判斷，因此推算的
    基準必須是**系統真實生效的值**而不是語料寫死的預設值，否則設定一改，助理就會
    信心十足地給出錯誤答案。這也是 `CLAUDE.md`「禁止寫死時間字面值，一律讀
    system_settings」這條硬性規則在 AI 助理這一側的落實。

    讀不到設定時回傳明確的說明而不是猜測值——讓模型知道「這次沒有即時設定可用」，
    比餵它一組可能過期的預設值安全。
    """
    if not settings:
        return "- （目前無法取得系統設定，回答涉及具體時間時請提醒使用者以系統顯示為準）"

    def _hhmm(value) -> str:
        text = str(value)
        return text[:5] if len(text) >= 5 else text

    return "\n".join(
        [
            f"- 表定上班時間：{_hhmm(settings.get('work_start_time'))}",
            f"- 表定下班時間：{_hhmm(settings.get('work_end_time'))}",
            f"- 午休時間：{_hhmm(settings.get('lunch_start_time'))}～{_hhmm(settings.get('lunch_end_time'))}",
            f"- 到班緩衝時間：{settings.get('grace_period_minutes')} 分鐘",
        ]
    )


def format_context(results: list) -> str:
    """把檢索結果組成送進 prompt 的 context 文字。

    每個片段都標上檔名與章節路徑，讓模型有辦法照規則 4 的格式逐字照抄來源。
    片段內容用 `content`（開頭已含 `【章節路徑】` 的 context prefix，與寫進 embedding
    的文字一致）。相似度分數不放進 context——那是給人看的除錯資訊，放進去只會誘導
    模型在答案裡談論分數。
    """
    blocks = []
    for index, result in enumerate(results, start=1):
        blocks.append(
            f"【片段 {index}】\n"
            f"檔名：{result.source_file}\n"
            f"章節路徑：{result.section_path}\n"
            f"內容：\n{result.content}"
        )
    return "\n\n".join(blocks)


def build_user_content(results: list, question: str, settings: dict | None = None) -> str:
    """組出送進 `generate()` 的使用者訊息（human prompt）。"""
    return _HUMAN_PROMPT.format(
        settings=format_settings(settings),
        context=format_context(results),
        question=question,
    )


def is_refusal(text: str) -> bool:
    """判斷一段回答是不是拒答（含語料自己寫的拒答措辭，見 `_REFUSAL_MARKERS` 說明）。"""
    if any(marker in text for marker in _REFUSAL_MARKERS):
        return True
    return _REFUSAL_PATTERN.search(text) is not None


_WEEKDAYS = ("星期一", "星期二", "星期三", "星期四", "星期五", "星期六", "星期日")


def build_system_prompt(
    today: date | None,
    *,
    has_team_tools: bool = False,
    with_tool_results: bool = False,
    has_context: bool = True,
) -> str:
    """組出批 B 的系統提示：既有規則 + 工具規則 + 今天是哪一天。

    `today` 必須來自虛擬時鐘。傳 `None` 時退回批 A 的提示（不帶工具規則）——
    拿不到日期卻仍然叫模型使用工具，它只會用自己認知的年份去推算區間，
    查出來是空的，然後很自然地告訴使用者「你那個月沒有任何出勤紀錄」。

    `with_tool_results=True` 只用在**模型已經呼叫過工具**的第二輪。
    原因見 `TOOL_RESULT_RULES` 的說明：那段規則出現在第一輪會讓政策問答的推算但書
    整片消失，這是 77 題 eval 實測出來的退化。
    """
    if today is None:
        return SYSTEM_PROMPT
    # 團隊查詢的規則二選一，依後端實際發出去的工具清單決定（見 _TEAM_TOOL_RULES 說明）。
    team_rules = _TEAM_TOOL_RULES if has_team_tools else _NO_TEAM_TOOL_RULES
    today_prompt = _TODAY_PROMPT.format(today=today.isoformat(), weekday=_WEEKDAYS[today.weekday()])

    # 檢索落空：以受限的 FALLBACK_PROMPT 為底，而不是 SYSTEM_PROMPT——沒有文件依據時
    # 絕不能讓模型談規定。規則 2 的推算但書在這條路徑沒有意義（這裡不准推算規定），不附。
    if not has_context:
        prompt = FALLBACK_PROMPT + _FALLBACK_TOOL_RULES + team_rules + today_prompt
        if with_tool_results:
            return prompt + _FALLBACK_TOOL_RESULT_NOTE + TOOL_RESULT_RULES
        return prompt

    prompt = SYSTEM_PROMPT + TOOL_RULES + team_rules + today_prompt
    # 第二輪帶工具結果時，那段「工具數字不加但書」必須是最後一句（它要壓過推算但書的
    # 提醒，而這一輪的數字確實來自工具）；第一輪則反過來，由推算但書收尾。
    if with_tool_results:
        return prompt + _DISCLAIMER_REMINDER + TOOL_RESULT_RULES
    return prompt + _DISCLAIMER_REMINDER
